# ---- formatting ---------------------------------------------------------------
def esc(text: object) -> str:
    return html.escape(str(text), quote=True)


def rich(text: str) -> str:
    """Escape, then turn `code` spans into <code>."""
    return re.sub(r"`([^`]+)`", r"<code>\1</code>", esc(text))


def n(x: float | None, nd: int = 1, unit: str = "") -> str:
    return NA if x is None else f"{x:,.{nd}f}{unit}"


def signed(x: float, nd: int, unit: str) -> str:
    text = f"{x:+,.{nd}f}"
    return f"{'0' if float(text) == 0 else text}{unit}"


def day(stamp: str | None) -> str:
    return stamp[:10] if stamp else NA


def when(unix_s: float | None) -> str:
    """UTC minute of a console timestamp (the evaluation stores unix seconds)."""
    return time.strftime("%Y-%m-%d %H:%M UTC", time.gmtime(unix_s)) if unix_s else NA


def link(href: str, label: str) -> str:
    return f'<a href="{esc(href)}" target="_blank" rel="noopener">{esc(label)}</a>'


def spark_path(values: list[float]) -> str:
    """SVG path in a 100 x 34 box from a list of numbers; empty when there is nothing to draw."""
    if len(values) < 2:
        return ""
    lo, hi = min(values), max(values)
    span = (hi - lo) or 1.0
    step = 100 / (len(values) - 1)
    pts = [f"{step * i:.0f} {30 - 26 * (v - lo) / span:.0f}" for i, v in enumerate(values)]
    return "M" + " L".join(pts)


# ---- values per key ------------------------------------------------------------
def _runs(bench: dict) -> dict:
    return {r["name"]: r for r in bench["runs"]}


def _level_rows(bench: dict) -> list[dict]:
    runs = _runs(bench)
    return [{"c": c, "tps": runs[f"baseline c={c}"]["summary"]["tokens_per_second"],
             "ttft": runs[f"baseline c={c}"]["summary"]["ttft_p95_s"],
             "cost": runs[f"baseline c={c}"]["summary"]["usd_per_million_tokens"],
             "gpu": runs[f"baseline c={c}"]["summary"]["gpu_util_avg"]} for c in LEVELS]


def _knee(levels: list[dict]) -> tuple[int, float]:
    for a, b in zip(levels, levels[1:]):
        gain = (b["tps"] / a["tps"] - 1) * 100
        if gain < KNEE_GAIN_PCT:
            return a["c"], gain
    return levels[-1]["c"], 0.0


def _seconds_between(a: str, b: str) -> int:
    from datetime import datetime
    fmt = "%Y-%m-%dT%H:%M:%S"
    return round((datetime.strptime(b[:19], fmt) - datetime.strptime(a[:19], fmt)).total_seconds())


def _helm_rows(revs: list[dict]) -> str:
    rows = []
    for i, r in enumerate(revs):
        change = esc(r.get("description", ""))
        if r.get("status") == "failed" and i + 1 < len(revs):
            change += f" &mdash; fixed in {_seconds_between(r['updated'], revs[i + 1]['updated'])} s"
        rows.append(f'<tr><td class="num">{esc(r["revision"])}</td><td>{esc(r.get("status", ""))}</td>'
                    f"<td>{change}</td></tr>")
    return "\n          ".join(rows)


def _eval_rows(result: dict) -> str:
    out = []
    for r in result["rows"]:
        ok = r.get("hit") if r["kind"] == "blog" else r.get("tool_ok")
        label = ("hit" if ok else "miss") if r["kind"] == "blog" else ("tool ok" if ok else "wrong tool")
        pill = "live" if ok else "firing"
        sources = ", ".join(link(s["url"], s["title"]) for s in r.get("sources", [])) or "none"
        detail = [f"<span>First tool: <code>{esc(r.get('first_tool') or 'none')}</code></span>",
                  f"<span>Sources cited: {sources}</span>",
                  f"<span>Claims supported: {esc(r.get('claims_supported'))} of {esc(r.get('claims_total'))}</span>",
                  f"<span>Answer: {esc(r.get('answer', ''))}</span>"]
        if r["kind"] == "platform" and r.get("facts_total"):
            detail.insert(3, f"<span>Expected facts stated: {esc(r.get('facts_stated'))} of {esc(r['facts_total'])}</span>")
        if r.get("judge_error"):
            detail.append(f"<span>Judge error: {esc(r['judge_error'])}</span>")
        out.append(f'<details class="row"><summary><span class="q">{esc(r["id"])} &middot; {esc(r["question"])}</span>'
                   f'<span class="pill {pill}">{label}</span><span>{r["latency_s"]:.1f} s</span></summary>'
                   f'<div>{"".join(detail)}</div></details>')
    return "\n        ".join(out)


def _cards() -> tuple[str, str]:
    cards = []
    for inc in INCIDENTS:
        rows = [("Symptom", "symptom"), ("Evidence", "evidence"), ("Root cause", "cause"), ("Fix", "fix"),
                ("Prevention", "prevention")]
        dl = "".join(f"<dt>{name}</dt><dd>{rich(inc[key])}</dd>" for name, key in rows)
        cards.append(f'<article class="card" data-layer="{inc["layer"]}"><span class="layer">{inc["layer"]}</span>'
                     f"<h3>{esc(inc['title'])}</h3><dl>{dl}</dl></article>")
    present = [layer for layer in LAYERS if any(i["layer"] == layer for i in INCIDENTS)]
    chips = ['<button class="chip" type="button" data-layer-filter="all" aria-pressed="true">all</button>']
    chips += [f'<button class="chip" type="button" data-layer-filter="{layer}">{layer}</button>' for layer in present]
    return "\n      ".join(cards), "\n      ".join(chips)


def _alert_rows() -> str:
    rows = []
    for name, rb in ALERT_RULES:
        href = f"docs/runbooks/{RUNBOOK_OF[rb]}.html"
        rows.append(f'<tr data-rule="{name}"><td><code>{name}</code></td>'
                    f'<td><span class="pill inactive" data-state>unknown</span></td>'
                    f'<td class="num" data-value>&mdash;</td><td>{link(href, rb)}</td></tr>')
    return "\n      ".join(rows)


