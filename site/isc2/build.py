def gather(root: Path = ROOT, python: str = sys.executable) -> dict:
    """Run the tests (any failure stops the build), read the measurements and the commit hash."""
    suites = {
        "console": (root / "console", ["-m", "pytest", "-q"]),
        # the tracked-pages test compares with the pages this build is about to replace
        "site": (root, ["-m", "pytest", "-q", "site", "--deselect",
                        "site/test_isc2.py::test_tracked_pages_equal_a_fresh_build_from_the_saved_inputs"]),
        "scripts": (root, ["-m", "pytest", "-q", "scripts/tests"]),
    }
    tests = {}
    for name, (cwd, args) in suites.items():
        done = subprocess.run([python, *args], cwd=cwd, capture_output=True, text=True)
        passed = re.search(r"(\d+) passed", done.stdout)
        if done.returncode != 0 or not passed:
            raise SystemExit(f"tests failed in {name}, build stopped:\n{done.stdout[-3000:]}{done.stderr[-1000:]}")
        tests[name] = int(passed.group(1))
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=root, capture_output=True, text=True,
                            check=True).stdout.strip()
    meas_dir = root / "docs" / "measurements"
    measurements = {p.stem: json.loads(p.read_text(encoding="utf8")) for p in sorted(meas_dir.glob("*.json"))} \
        if meas_dir.exists() else {}
    bench = json.loads((root / "docs" / "benchmark-results.json").read_text(encoding="utf8"))
    return {"commit": commit, "tests": tests, "benchmark": bench, "measurements": measurements}


def main(out: Path = OUT, from_inputs: bool = False) -> None:
    if from_inputs:
        inputs = json.loads(INPUTS.read_text(encoding="utf8"))
    else:
        inputs = gather()
        INPUTS.write_text(json.dumps(inputs, indent=2, sort_keys=True, ensure_ascii=True) + "\n", encoding="utf8")
    pages = render(inputs)
    if out.exists():
        shutil.rmtree(out)
    for rel, text in pages.items():
        p = out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf8")
    print("built", len(pages), "files into", out)


if __name__ == "__main__":
    main(from_inputs="--from-inputs" in sys.argv)
